// upstream bundles its `i-custom:privateersclub` glyph (a 1200px png inside an
// svg) into the css; a 64px webp of the same image ships as a static asset
const IMAGE_ICONS: Record<string, string> = {
  'custom:privateersclub': '/upstream/privateersclub.webp',
}

// `i-lucide:globe` / `i-lucide-globe` / `lucide:globe` → `lucide:globe`
function iconKey(name: string): string {
  const bare = name.trim().replace(/^i-/, '')
  if (bare.includes(':')) return bare
  // dash form: the set is everything up to the first dash that yields a known key
  for (let i = bare.indexOf('-'); i !== -1; i = bare.indexOf('-', i + 1)) {
    const key = `${bare.slice(0, i)}:${bare.slice(i + 1)}`
    if (key in ICONS || key in IMAGE_ICONS) return key
  }
  return bare
}

export function hasIcon(name: string | undefined): boolean {
  if (!name) return false
  const key = iconKey(name)
  return key in ICONS || key in IMAGE_ICONS
}

export function IconifyIcon({
  name,
  size = 16,
  className,
  color,
}: {
  name: string
  size?: number
  className?: string
  color?: string
}) {
  const key = iconKey(name)
  const image = IMAGE_ICONS[key]
  if (image) {
    return (
      <img
        src={image}
        alt=""
        aria-hidden="true"
        width={size}
        height={size}
        className={className}
        draggable={false}
      />
    )
  }
  const icon = ICONS[key] ?? ICONS['lucide:globe']!
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      viewBox={icon[0]}
      width={size}
      height={size}
      aria-hidden="true"
      className={className}
      style={color ? { color } : undefined}
      dangerouslySetInnerHTML={{ __html: icon[1] }}
    />
  )
}
